//! Immutable character facts for locale location formatting; no model generation.
fn main() {
    assert_eq!(
        std::char::UNICODE_VERSION,
        (17, 0, 0),
        "Review Unicode baseline changes explicitly"
    );
    let mut lowers = Vec::new();
    let mut expansions = Vec::new();
    let mut uppers = Vec::new();
    for code in 0..=0x10ffff {
        let Some(c) = char::from_u32(code) else {
            continue;
        };
        if c.is_uppercase() {
            uppers.push(code);
        }
        let lower: Vec<u32> = c.to_lowercase().map(u32::from).collect();
        if lower.len() == 1 {
            if lower[0] != code {
                lowers.push((code, lower[0] as i32 - code as i32));
            }
        } else {
            expansions.push((code, lower));
        }
    }
    let mut ranges = Vec::new();
    let mut i = 0;
    while i < lowers.len() {
        let (first, delta) = lowers[i];
        let mut last = first;
        let mut step = 1;
        if i + 1 < lowers.len() && lowers[i + 1].1 == delta && lowers[i + 1].0 - first <= 2 {
            step = lowers[i + 1].0 - first;
            while i + 1 < lowers.len() && lowers[i + 1].1 == delta && lowers[i + 1].0 - last == step
            {
                i += 1;
                last = lowers[i].0;
            }
        }
        ranges.push((first, last, step, delta));
        i += 1;
    }
    let mut upper_ranges = Vec::new();
    for code in uppers {
        if let Some((_, last)) = upper_ranges
            .last_mut()
            .filter(|(_, last)| *last + 1 == code)
        {
            *last = code;
        } else {
            upper_ranges.push((code, code));
        }
    }
    println!(
        "// Rust Unicode {:?}; generated by unicode_language_table.rs.\n#pragma once\n#include <array>\n#include <cstdint>\nnamespace teaql::detail {{",
        std::char::UNICODE_VERSION
    );
    println!(
        "struct LanguageCaseRange {{ char32_t first,last; std::uint32_t step; std::int32_t delta; }};"
    );
    println!(
        "inline constexpr std::array<LanguageCaseRange,{}> language_lower_ranges{{{{",
        ranges.len()
    );
    for (first, last, step, delta) in ranges {
        println!("    {{0x{first:X},0x{last:X},{step},{delta}}},");
    }
    println!(
        "}}}};\nstruct LanguageUpperRange {{ char32_t first,last; }};\ninline constexpr std::array<LanguageUpperRange,{}> language_upper_predicates{{{{",
        upper_ranges.len()
    );
    for (first, last) in upper_ranges {
        println!("    {{0x{first:X},0x{last:X}}},");
    }
    println!(
        "}}}};\nstruct LanguageLowerExpansion {{ char32_t source; std::array<char32_t,3> target; }};\ninline constexpr std::array<LanguageLowerExpansion,{}> language_lower_expansions{{{{",
        expansions.len()
    );
    for (source, mut target) in expansions {
        target.resize(3, 0);
        println!(
            "    {{0x{source:X},{{0x{:X},0x{:X},0x{:X}}}}},",
            target[0], target[1], target[2]
        );
    }
    println!("}}}};\n}}");
}
