#!/usr/bin/env python3
"""Verify every static E-entry argument against its complete preserved SDK."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
from expression_entry_qualification import verify_file
from query_result_marker_qualification import without_current as without_markers
ROOT=Path(__file__).resolve().parents[1]
SNAPSHOT=ROOT/'docs/parity/expression_entry_sdks_before_fix_5_0_6.json.gz'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--report',type=Path)
    args=parser.parse_args()
    snapshot=json.loads(gzip.decompress(SNAPSHOT.read_bytes()))
    records=[]
    for directory,files in snapshot.items():
        target=ROOT/directory
        assert {str(p.relative_to(target)) for p in target.rglob('*') if p.is_file()}==files.keys(),directory
        manifest_name='manifest.json' if 'manifest.json' in files else 'PROVENANCE.json'
        manifest=json.loads((target/manifest_name).read_text())
        changes=[];entries=0
        for name,previous in files.items():
            if name==manifest_name:continue
            generated=(target/name).read_text()
            assert hashlib.sha256(generated.encode()).hexdigest()==manifest['files'][name],(directory,name)
            entries+=verify_file(ROOT,name,previous,generated)
            if previous!=without_markers(ROOT,name,generated):changes.append(name)
        assert len(changes)==(1 if entries else 0),(directory,changes)
        records.append(dict(directory=directory,changed_files=changes,entry_arguments=entries))
    assert len(records)==77
    print('Verified static E-entry arguments across',len(records),'complete SDKs;',sum(row['entry_arguments'] for row in records),'factories; every other generated byte is unchanged')
    if args.report:
        assert not args.report.exists()
        args.report.write_text(json.dumps(dict(schema=1,snapshot_sha256=hashlib.sha256(SNAPSHOT.read_bytes()).hexdigest(),records=records),indent=2)+'\n')


if __name__=='__main__':main()
