#!/usr/bin/env python3
"""Reproduce all active SDKs with restricted Context hydration adapter updates."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile
from reproduce_cpp_contract_fixtures import FAMILIES

ROOT = Path(__file__).resolve().parents[1]
PRODUCER = ROOT.parent / 'teaql_code_gen_cpp'


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def file_map(directory, manifest):
    return {str(p.relative_to(directory)): digest(p) for p in sorted(directory.rglob('*'))
            if p.is_file() and p.name != manifest}


def restore_adapters(text, name):
    """Undo only the reviewed move, consuming graph binding and original-row transfer."""
    counts = dict(allocator_moves=0, original_rows=0, consuming_graph_bindings=0)
    if name.endswith('/models.hpp'):
        pattern = r'([A-Za-z_][A-Za-z_0-9]*)\(\s*detail::move_to\(a\.resource\(\),\s*std::move\(other\)\)\)'
        text, counts['allocator_moves'] = re.subn(
            pattern, lambda match: match[1] + '(std::allocator_arg, a, std::as_const(other))', text)
        text, counts['original_rows'] = re.subn(
            r'set_original_compact_row\(ENTITY_NAME,\s*std::move\(row\)\)',
            'set_original_compact_row(ENTITY_NAME, row)', text)
    elif name.endswith('/support.hpp'):
        old = 'root = std::move(root).with_shared_graph(*source);'
        counts['consuming_graph_bindings'] = text.count(old)
        text = text.replace(old, 'root = root.with_shared_graph(*source);')
    if not sum(counts.values()):
        raise RuntimeError('No reviewed hydration adapter in changed file')
    return text, counts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--apply', action='store_true', help='Permit only the three reviewed hydration adapter changes')
    mode.add_argument('--refresh-provenance', action='store_true',
                      help='Refresh producer fingerprints only; require every generated byte unchanged')
    parser.add_argument('--record', type=Path, required=True)
    args = parser.parse_args()
    if args.record.exists():
        parser.error('Use a fresh report; preserve historical evidence')
    record = dict(scope=('All active SDK reproduction; unchanged artifacts with refreshed provenance'
                         if args.refresh_provenance else
                         'All active SDK reproduction; narrow hydration adapter change proof'),
                  complete=False, apply=args.apply, refresh_provenance=args.refresh_provenance,
                  steps=[], sdks=[])

    def save():
        args.record.write_bytes(gzip.compress((json.dumps(record, indent=2) + '\n').encode(), mtime=0))

    def run(command, cwd=ROOT):
        result = subprocess.run([str(x) for x in command], cwd=cwd, text=True, capture_output=True)
        record['steps'].append(dict(command=[str(x) for x in command], cwd=str(cwd),
                                    exit_code=result.returncode, stdout=result.stdout, stderr=result.stderr))
        save()
        result.check_returncode()
        return result.stdout

    record['qualified_hydration_receipts'] = {}
    for profile in ('native', 'sanitize'):
        prerequisite_path = ROOT / ('docs/parity/hydration_allocation_combined_' + profile + '_5_0_6.json.gz')
        prerequisite = json.loads(gzip.decompress(prerequisite_path.read_bytes()))
        assert prerequisite['complete'] and not prerequisite['source_promoted']
        assert prerequisite['budget_ceilings_passed']
        assert digest(ROOT / 'tests/parity/hydration_allocation_probe.cpp') == prerequisite['source_sha256']
        expected_grid = {(path, projection, size) for path in ('typed_hydration', 'context_hydration', 'identity_batch', 'plain_hydration')
                         for projection in ('sparse', 'full') for size in (1, 100, 10000)}
        assert len(prerequisite['rows']) == 24 and {tuple(row[:3]) for row in prerequisite['rows']} == expected_grid
        for name, expected in prerequisite['runtime_inputs_sha256'].items():
            assert digest(ROOT / name) == expected, name
        for name, expected in prerequisite['generated_sha256'].items():
            assert digest(ROOT / name) == expected, name
        for path, projection, rows, requests, _, heap, _, _ in prerequisite['rows']:
            ceiling = {'typed_hydration': 3 * rows + 1, 'context_hydration': 2 * rows + 1,
                       'identity_batch': 3 * rows + 32}.get(path)
            if ceiling is not None:
                assert requests <= ceiling and heap <= ceiling, (profile, path, projection, rows)
        record['qualified_hydration_receipts'][profile] = digest(prerequisite_path)
    kernel_path = ROOT / 'docs/parity/combined_cleanup_runtime_5_0_6.json.gz'
    kernel = json.loads(gzip.decompress(kernel_path.read_bytes()))
    assert kernel['complete'] and not kernel['source_promoted']
    expected_tests = {'context_memory_contracts', 'context_reference_contracts', 'entity_runtime_contracts',
                      'async_context_contracts', 'context_dispatch_shutdown_contracts',
                      'loaded_view_move_context_contracts', 'loaded_view_move_rust_parity', 'state_cache_cost_contracts',
                      'entity_runtime_model_contracts', 'entity_runtime_model_rust_parity',
                      'runtime_graph_model_contracts', 'runtime_graph_model_rust_parity',
                      'runtime_graph_contracts', 'runtime_graph_rust_parity', 'entity_runtime_rust_parity'}
    for profile in ('native', 'sanitize'):
        assert set(kernel['profiles'][profile]['tests']) == expected_tests
    for name, expected in kernel['inputs_sha256'].items():
        assert digest(ROOT / name) == expected, name
    record['qualified_kernel_receipt_sha256'] = digest(kernel_path)
    provenance = json.loads((ROOT / 'tests/generator/parity/hydration_allocation_contracts/cpp/PROVENANCE.json').read_text())
    producer_inputs = provenance['generator_implementation_sha256']
    for name, expected in producer_inputs.items():
        assert digest(PRODUCER / name) == expected, name
    record['producer_inputs'] = producer_inputs
    run(['python3', 'scripts/verify_upstream.py'])
    run(['mvn', '-q', '-pl', 'generator', '-am', '-DskipTests', 'package'], PRODUCER)
    entries = [(ROOT / 'examples/generated', 'manifest.json', None)]
    entries += [(p.parent, 'manifest.json', None) for p in sorted((ROOT / 'tests').glob('generated_*/manifest.json'))]
    for family, probe in FAMILIES.items():
        entries += [(p.parent, 'PROVENANCE.json', probe)
                    for p in sorted((ROOT / 'tests/generator/parity' / family).glob('*/cpp/PROVENANCE.json'))]
    entries += [(ROOT / 'tests/generator/parity' / family / 'cpp', 'PROVENANCE.json', 'TypeConfigurationProbe')
                for family in ['query_alias_contracts', 'relation_identity_contracts', 'expression_root_contracts', 'graph_serialization_contracts', 'hydration_allocation_contracts']]
    active = {directory for directory, _, _ in entries}
    protected = {}
    for provenance in (ROOT / 'tests/generator/parity').rglob('PROVENANCE.json'):
        if provenance.parent in active:
            continue
        source = json.loads(provenance.read_text())
        for name, expected in source['files'].items():
            path = provenance.parent / name
            if digest(path) != expected:
                raise RuntimeError(f'Changed protected artifact: {path}')
            protected[str(path.relative_to(ROOT))] = expected
        protected[str(provenance.relative_to(ROOT))] = digest(provenance)
    record['protected_artifacts'] = protected
    staged = []
    with tempfile.TemporaryDirectory(prefix='teaql_generated_hydration_', dir='/dev/shm') as temporary:
        work = Path(temporary)
        cp_file = work / 'classpath.txt'
        run(['mvn', '-q', '-pl', 'generator', 'dependency:build-classpath', f'-Dmdep.outputFile={cp_file}'], PRODUCER)
        classpath = ':'.join(str(PRODUCER / p) for p in ['generator/target/classes', 'model/target/classes'])
        classpath += ':' + cp_file.read_text().strip()
        run(['javac', '-cp', classpath, '-d', work,
             *(ROOT / 'tests/generator' / (probe + '.java') for probe in sorted(set(FAMILIES.values())))])
        classpath = str(work) + ':' + classpath
        formatter = ROOT / '.tools/clang-format/bin/clang-format'
        for index, (destination, manifest_name, probe) in enumerate(entries):
            previous = json.loads((destination / manifest_name).read_text())
            before = file_map(destination, manifest_name)
            if before != previous['files']:
                raise RuntimeError(f'Artifact/provenance mismatch: {destination}')
            output = work / 'outputs' / str(index)
            model = ROOT / previous['model']
            if digest(model) != previous['model_sha256']:
                raise RuntimeError(f'Model changed: {model}')
            command = ['java', '-cp', classpath, probe or 'com.skynet.codegenerator.cpp.CppCoreGenerator']
            run([*command, *(['cpp'] if probe else []), model, output], PRODUCER)
            headers = sorted(output.rglob('*.hpp'))
            if headers:
                run([formatter, f'--style=file:{ROOT / ".clang-format"}', '--Werror', '-i', *headers])
            after = file_map(output, manifest_name)
            if before.keys() != after.keys():
                raise RuntimeError(f'Changed SDK file set: {destination}')
            changes = []
            for name in before:
                if before[name] == after[name]:
                    continue
                if not args.apply or not name.endswith(('/models.hpp', '/support.hpp')):
                    raise RuntimeError(f'Unexpected generated change: {destination}/{name}')
                restored, counts = restore_adapters((output / name).read_text(), name)
                result = subprocess.run([str(formatter), f'--style=file:{ROOT / ".clang-format"}',
                                         '--Werror', '--assume-filename=' + name],
                                        input=restored, text=True, capture_output=True, check=True)
                if result.stdout != (destination / name).read_text():
                    raise RuntimeError(f'Hydration adapter changed another body: {destination}/{name}')
                changes.append(dict(file=name, **counts))
                staged.append((destination / name, (output / name).read_bytes()))
            current = dict(previous, files=after)
            current['generator_implementation_sha256'] = {
                path: digest(PRODUCER / path) for path in previous['generator_implementation_sha256']}
            manifest = (json.dumps(current, indent=2) + '\n').encode()
            if not (args.apply or args.refresh_provenance) and manifest != (destination / manifest_name).read_bytes():
                raise RuntimeError(f'Stale generator provenance: {destination}')
            staged.append((destination / manifest_name, manifest))
            record['sdks'].append(dict(path=str(destination.relative_to(ROOT)), changes=changes,
                                       manifest=manifest_name, before_manifest_sha256=digest(destination / manifest_name),
                                       model=previous['model'], model_sha256=previous['model_sha256'],
                                       before=before, after=after))
            save()
            print('Reproduced', destination.relative_to(ROOT), flush=True)
    for name, expected in producer_inputs.items():
        assert digest(PRODUCER / name) == expected, name
    for name, expected in prerequisite['runtime_inputs_sha256'].items():
        assert digest(ROOT / name) == expected, name
    for sdk in record['sdks']:
        destination = ROOT / sdk['path']
        assert file_map(destination, sdk['manifest']) == sdk['before'], sdk['path']
        assert digest(destination / sdk['manifest']) == sdk['before_manifest_sha256'], sdk['path']
        assert digest(ROOT / sdk['model']) == sdk['model_sha256'], sdk['model']
    if args.apply or args.refresh_provenance:
        for path, data in staged:
            if path.read_bytes() != data:
                path.write_bytes(data)
    for relative, expected in protected.items():
        if digest(ROOT / relative) != expected:
            raise RuntimeError(f'Protected source/historical output changed: {relative}')
    record['complete'] = True
    save()
    print('Qualified complete SDK reproduction:', len(entries), 'SDKs;',
          ('only reviewed hydration adapters permitted' if args.apply else
           'all generated bytes unchanged; refreshed fingerprints' if args.refresh_provenance else
           'every byte identical'), flush=True)


if __name__ == '__main__':
    main()
