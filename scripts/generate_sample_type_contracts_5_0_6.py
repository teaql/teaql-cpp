#!/usr/bin/env python3
"""Generate or reproduce ordinary-entity configured-type sample fixtures."""
import argparse
import hashlib
import json
import re
import shutil
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'tests/generator/parity/sample_type_configuration_contracts'


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def files(directory):
    return {path.relative_to(directory).as_posix(): digest(path)
            for path in directory.rglob('*') if path.is_file() and path.name != 'PROVENANCE.json'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--refresh-cpp-operand', action='store_true')
    args = parser.parse_args()
    if args.check and args.refresh_cpp_operand:
        parser.error('Checking cannot refresh retained artifacts')
    subprocess.run(['python3', str(ROOT / 'scripts/verify_upstream.py')], check=True)
    reference = ROOT / '.reference/teaql_code_gen'
    producer = ROOT.parent / 'teaql_code_gen_cpp'
    lock = json.loads((producer / 'cpp_generator.lock.json').read_text())
    assert subprocess.check_output(['git', '-C', str(reference), 'rev-parse', 'HEAD'], text=True).strip() == lock['generator_baseline_commit']
    assert not subprocess.check_output(['git', '-C', str(reference), 'status', '--porcelain'])
    paths = {'rust': (reference, Path('/tmp/teaql_constant_metadata_original_classpath.txt')),
             'cpp': (producer, Path('/tmp/teaql_constant_metadata_cpp_classpath.txt'))}
    classpaths = {language: ':'.join(str(repository / path) for path in
                  ('generator/target/classes', 'model/target/classes')) + ':' + classpath.read_text().strip()
                  for language, (repository, classpath) in paths.items()}
    formatter = ROOT / '.tools/clang-format/bin/clang-format'
    assert 'version 18.1.8' in subprocess.check_output([str(formatter), '--version'], text=True)
    with tempfile.TemporaryDirectory(prefix='teaql_sample_type_generation_') as temporary:
        work = Path(temporary)
        subprocess.run(['javac', '-cp', classpaths['rust'], '-d', str(work),
                        str(ROOT / 'tests/generator/TypeConfigurationProbe.java')], check=True)
        # Bind the frozen compiled producer to an existing complete original SDK.
        original = ROOT / 'tests/generator/parity/type_configuration_contracts/numeric_alias'
        control = work / 'control'
        subprocess.run(['java', '-cp', str(work) + ':' + classpaths['rust'],
                        'TypeConfigurationProbe', 'rust', str(original / 'model.xml'), str(control)],
                       stdout=subprocess.DEVNULL, check=True)
        assert files(control) == json.loads((original / 'rust/PROVENANCE.json').read_text())['files']
        for case in json.loads((BASE / 'cases.json').read_text()):
            model = BASE / case / 'model.xml'
            for language in ('rust', 'cpp'):
                output = work / case / language
                subprocess.run(['java', '-cp', str(work) + ':' + classpaths[language],
                                'TypeConfigurationProbe', language, str(model), str(output)],
                               stdout=subprocess.DEVNULL, check=True)
                observation = json.loads((output / 'OBSERVATION.json').read_text())
                assert observation['generated'], observation
                if language == 'cpp':
                    subprocess.run([str(formatter), f'--style=file:{ROOT / ".clang-format"}',
                                    '--Werror', '-i', *(str(p) for p in output.rglob('*.hpp'))], check=True)
                provenance = dict(generator_commit=lock['generator_baseline_commit'],
                                  runtime_commit=lock['runtime_rust_baseline'], hand_edited=False,
                                  model=str(model.relative_to(ROOT)), model_sha256=digest(model), files=files(output))
                if language == 'cpp':
                    provenance['formatter'] = '18.1.8'
                    implementation = 'generator/src/main/java/com/skynet/codegenerator/cpp/CppCoreGenerator.java'
                    provenance['generator_implementation_sha256'] = {implementation: digest(producer / implementation)}
                target = BASE / case / language
                if args.check or (args.refresh_cpp_operand and language == 'rust'):
                    assert files(target) == provenance['files'], f'Changed generated bytes: {case}/{language}'
                    assert json.loads((target / 'PROVENANCE.json').read_text()) == provenance
                elif args.refresh_cpp_operand:
                    retained = json.loads((target / 'PROVENANCE.json').read_text())
                    assert files(target) == retained['files'], f'Retained SDK changed: {case}'
                    changed = {name for name in provenance['files']
                               if provenance['files'][name] != retained['files'].get(name)}
                    assert set(provenance['files']) == set(retained['files'])
                    if 'ASSIST.md' in changed:
                        assert case == 'numeric_alias'
                        addition = "Numeric sample recipes for String-mapped aliases retain the original integer operand. Generated typed Checkers can reject entity materialization before custom CheckerLogic runs. The runtime does not silently convert the operand to text; modules without those checkers retain the provider's actual behavior. Use explicitly typed application values when this model's sample save fails.\n"
                        guide = (output / 'ASSIST.md').read_text()
                        assert guide.count(addition) == 1
                        assert guide.replace(addition, '') == (target / 'ASSIST.md').read_text()
                        shutil.copyfile(output / 'ASSIST.md', target / 'ASSIST.md')
                        changed.remove('ASSIST.md')
                    if changed:
                        expected_path = f'include/cpp_sample_types_{case}/sample_data.hpp'
                        assert case == 'numeric_alias' and changed == {expected_path}, changed
                        previous = (target / expected_path).read_text()
                        generated = (output / expected_path).read_text()
                        pattern = r'\{\s*auto original\s*=\s*GeneratedSampleValues::number\([^;]*;.*?\n\s*\}'
                        before = re.findall(pattern, previous, re.S)
                        after = re.findall(pattern, generated, re.S)
                        assert len(before) == len(after) == 2
                        assert all('unconverted_value' in block for block in after)
                        restored = generated
                        for new, old in zip(after, before):
                            restored = restored.replace(new, old, 1)
                        assert restored == previous, 'Operand repair changed unrelated generated code'
                        history = target.parent / 'cpp_before_operand_fix'
                        assert not history.exists()
                        shutil.copytree(target, history)
                        shutil.copyfile(output / expected_path, target / expected_path)
                    (target / 'PROVENANCE.json').write_text(json.dumps(provenance, indent=2) + '\n')
                else:
                    assert not target.exists(), f'Refusing to overwrite retained SDK: {target}'
                    shutil.copytree(output, target)
                    (target / 'PROVENANCE.json').write_text(json.dumps(provenance, indent=2) + '\n')
                action = 'Verified' if args.check or (args.refresh_cpp_operand and language == 'rust') else 'Refreshed' if args.refresh_cpp_operand else 'Generated'
                print(f'{action} {case}/{language}: {len(provenance["files"])} files', flush=True)


if __name__ == '__main__':
    main()
